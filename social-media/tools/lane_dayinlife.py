"""Day-in-the-life infographic - one illustrated 4:5 card per intern role.

The illustration is generated by OpenAI's image model with NO text in it (the
model misspells words); every word on the card is rendered here in brand fonts,
so titles, times and tools stay accurate and editable.

Each role is one spec in content/dayinlife/<slug>.json:
  structure   what the cut-away building is (office tower, giant phone, ...)
  character   the intern who appears on every floor
  scenes      five floor scenes, ground floor (morning) first
  props       floating props around the building
  steps       five cards: time, title, body, the illustration point the leader
              line goes to ("target", source pixels) and the card box ("card",
              canvas x, y, width). Card positions are set per image after a look.
  tools, tools_card, cta

    python3 tools/lane_dayinlife.py generate accounting     # image model -> assets/dayinlife/accounting.png
    python3 tools/lane_dayinlife.py render accounting OUT.png
"""
import os, sys, json, base64
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import lanes_common as L
from PIL import Image

SPECS = os.path.join(L.BASE, "content", "dayinlife")
ART = os.path.join(L.BASE, "assets", "dayinlife")
W, H = 1080, 1350                     # 4:5, the tallest ratio Instagram shows uncropped
NAVY, DEEP, AMBER, CORAL, INK = "#0E2141", "#0A1830", "#FFB120", "#FF6B6B", "#152743"

STYLE = (
    "Flat vector editorial infographic illustration in a rich, playful, detailed style, like an "
    "award-winning magazine infographic. NO TEXT of any kind.\n\n"
    "The background is split down the middle: the left half is bright morning daylight (light sky "
    "blue with soft white clouds and small pine trees), the right half is evening (deep navy night "
    "sky with small stars and a crescent moon). The structure straddles the split.\n\n")
RULES = (
    "\n\nComposition: keep the outer left and right margins (about 18% of the width on each side) as "
    "plain background with only a few small props, clouds or stars, and keep the top 15% as plain "
    "background. These areas will hold text added later.\n\n"
    "Palette: deep navy #0E2141, amber #FFB120, coral #FF6B6B, mint #7FDBB6, sky blue #5FA7E5, "
    "cream #FAF5EC, plus warm brick orange and soft brown accents. Clean flat shapes, subtle shading, "
    "no heavy outlines, consistent lighting.\n\n"
    "Absolutely no words, letters, numbers, logos or signage anywhere. Screens, documents and "
    "folders show only abstract lines and blocks.")
FLOOR = ["Bottom floor (morning)", "Second floor", "Third floor", "Fourth floor", "Top floor (evening side)"]


def load(slug):
    return json.load(open(os.path.join(SPECS, slug + ".json")))


def prompt(spec):
    scenes = "\n".join(f"{i + 1}. {FLOOR[i]}: {s}" for i, s in enumerate(spec["scenes"]))
    return (STYLE + f"Scene: {spec['structure']}\n\nInside it, five stacked floors, each a small vignette "
            f"of the SAME {spec['character']} moving through the working day, connected floor to floor "
            f"by a winding orange staircase and ladders:\n{scenes}\n\n"
            f"Around it, floating decorative props that link the scenes: {spec['props']}." + RULES)


def generate(slug, out=None):
    """One image-model call (spends OpenAI credits). Writes assets/dayinlife/<slug>.png."""
    for path in (os.path.join(L.BASE, ".env"),):
        if os.path.exists(path):
            for line in open(path):
                line = line.strip()
                if line and not line.startswith("#") and "=" in line:
                    k, v = line.split("=", 1)
                    os.environ.setdefault(k.strip(), v.strip())
    from openai import OpenAI
    client = OpenAI()
    out = out or os.path.join(ART, slug + ".png")
    os.makedirs(os.path.dirname(out), exist_ok=True)
    model = os.getenv("OPENAI_IMAGE_MODEL", "gpt-image-2")
    r = client.images.generate(model=model, prompt=prompt(load(slug)), size="1024x1536", quality="high")
    open(out, "wb").write(base64.b64decode(r.data[0].b64_json))
    print("generated", os.path.relpath(out, L.BASE), "with", model)
    return out


def _step(st, s, ox):
    cx, cy = ox + st["target"][0] * s, st["target"][1] * s
    x, y, w = st["card"]
    ax = x if x > W / 2 else x + w        # the line leaves from the card edge facing the scene
    ay = y + 22
    pill = CORAL if st.get("accent") == "coral" else NAVY
    return (f"<svg style='position:absolute;left:0;top:0;' width='{W}' height='{H}'>"
            f"<line x1='{ax}' y1='{ay}' x2='{cx}' y2='{cy}' stroke='#fff' stroke-width='3' stroke-dasharray='2 7' stroke-linecap='round'/>"
            f"<circle cx='{cx}' cy='{cy}' r='9' fill='{AMBER}' stroke='{DEEP}' stroke-width='3'/></svg>"
            f"<div style='position:absolute;left:{x}px;top:{y}px;width:{w}px;box-sizing:border-box;padding:11px 13px 13px;"
            f"background:#FFFFFF;border:3px solid {DEEP};border-radius:16px;box-shadow:6px 6px 0 rgba(10,24,48,.45);'>"
            f"<div style='display:flex;align-items:center;gap:10px;'>"
            f"<span style=\"flex:none;width:30px;height:30px;border-radius:50%;background:{AMBER};border:2px solid {DEEP};display:flex;"
            f"align-items:center;justify-content:center;font-family:Inter;font-weight:900;font-size:17px;color:{DEEP};\">{st['n']}</span>"
            f"<span style=\"font-family:Inter;font-weight:900;font-size:22px;color:#fff;background:{pill};"
            f"padding:1px 9px;border-radius:7px;\">{st['time']}</span></div>"
            f"<div style=\"font-family:Inter;font-weight:800;font-size:22px;color:{INK};letter-spacing:-.3px;line-height:1.08;margin-top:8px;\">{st['title']}</div>"
            f"<div style=\"font-family:'DM Sans';font-weight:600;font-size:19px;line-height:1.22;color:#3A4A63;margin-top:4px;\">{st['body']}</div></div>")


def render(slug, out):
    spec = load(slug)
    src = os.path.join(ART, slug + ".png")
    im = Image.open(src)
    s = H / im.height                    # illustration fills the height; side bands carry the two skies
    iw = round(im.width * s)
    ox = (W - iw) // 2
    bg = (f"<div style='position:absolute;left:0;top:0;width:560px;height:{H}px;background:linear-gradient(180deg,#68BEEF,#A6EEEF);'></div>"
          f"<div style='position:absolute;left:540px;top:0;width:540px;height:{H}px;background:#032E58;'></div>"
          f"<img src='{L.img(src)}' style='position:absolute;left:{ox}px;top:0;width:{iw}px;height:{H}px;'>")
    article = spec.get("article", "A")
    # A narrow title column wraps the kicker; break it on purpose so "A" is never left alone.
    brk = "<br>" if spec.get("title_width", 480) < 420 else " "
    kicker = f"A DAY IN THE LIFE{brk}OF {article.upper()}"
    title = (f"<div style='position:absolute;left:34px;top:30px;width:{spec.get('title_width', 480)}px;'>"
             f"<div style=\"font-family:'DM Sans';font-weight:800;font-size:21px;line-height:1.3;letter-spacing:5px;color:{INK};\">{kicker}</div>"
             f"<div style=\"font-family:Inter;font-weight:900;font-size:{spec.get('title_size', 64)}px;line-height:.98;letter-spacing:-2px;color:{INK};margin-top:8px;\">"
             f"{spec['role_line1']}<br><span style='color:#D8433B;'>{spec['role_line2']}</span></div></div>")
    # A soft navy glow keeps the white logo legible over a moon or bright prop.
    logo = (f"<div style='position:absolute;right:-40px;top:-40px;width:480px;height:220px;"
            f"background:radial-gradient(closest-side,rgba(3,30,62,.9),rgba(3,30,62,0));'></div>"
            f"<img src='{L.WHT}' style='position:absolute;right:30px;top:28px;height:{L.LOGO}px;'>")
    steps = "".join(_step(st, s, ox) for st in spec["steps"])
    tools = ""
    if spec.get("tools"):
        x, y, w = spec["tools_card"]
        chips = "".join(f"<span style=\"display:inline-block;margin:6px 6px 0 0;padding:5px 12px;border-radius:14px;background:{AMBER};"
                        f"font-family:Inter;font-weight:800;font-size:19px;color:{DEEP};\">{t}</span>" for t in spec["tools"])
        tools = (f"<div style='position:absolute;left:{x}px;top:{y}px;width:{w}px;box-sizing:border-box;padding:14px 16px 16px;"
                 f"background:rgba(10,24,48,.82);border:2px solid rgba(255,255,255,.25);border-radius:16px;'>"
                 f"<div style=\"font-family:'DM Sans';font-weight:800;font-size:17px;letter-spacing:4px;color:{AMBER};\">TOOLS YOU USE</div>"
                 f"{chips}</div>")
    foot = (f"<div style='position:absolute;left:0;right:0;bottom:0;height:84px;background:{DEEP};display:flex;align-items:center;"
            f"justify-content:space-between;padding:0 34px;box-sizing:border-box;'>"
            f"<span style=\"font-family:Inter;font-weight:800;font-size:26px;color:#fff;\">{spec['cta']}</span>"
            f"<span style=\"font-family:'DM Sans';font-weight:800;font-size:24px;color:{AMBER};\">{L.URL}</span></div>")
    return L.render(os.path.dirname(os.path.abspath(out)), os.path.basename(out),
                    bg + title + logo + steps + tools + foot, w=W, h=H)


if __name__ == "__main__":
    cmd, slug = sys.argv[1], sys.argv[2]
    if cmd == "generate":
        generate(slug)
    elif cmd == "prompt":
        print(prompt(load(slug)))
    elif cmd == "render":
        render(slug, sys.argv[3] if len(sys.argv) > 3 else os.path.join(L.BASE, "test_output_infographic", f"dayinlife_{slug}.png"))
